// board.mjs — the one project list, built from disk on every call, and its STATUS.md rendering.
import fs from 'node:fs';
import path from 'node:path';
import { startPrompt } from './prompt.mjs';
import { buildQueue } from './queue.mjs';
import { allStatuses, nextUp } from './status.mjs';
import { buildWorld } from './world.mjs';

function readFrontmatter(text) {
  const m = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  const fm = {};
  if (m) for (const line of m[1].split(/\r?\n/)) {
    const kv = line.match(/^(\w+):\s*(.*)$/);
    if (kv) fm[kv[1]] = kv[2].trim();
  }
  return fm;
}

// Old hand-written cards for projects that have no graph yet. Their typed state is not shown.
function legacyCards(home, graphed) {
  const dir = path.join(home, 'projects');
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir)
    .filter((f) => f.endsWith('.md') && !graphed.has(f.replace(/\.md$/, '')))
    .map((f) => {
      const fm = readFrontmatter(fs.readFileSync(path.join(dir, f), 'utf8'));
      return { slug: f.replace(/\.md$/, ''), name: fm.project || f, cardUpdated: fm.updated || '', folder: fm.folder || '' };
    })
    .sort((a, b) => a.name.localeCompare(b.name));
}

function countBy(statuses) {
  const counts = {};
  for (const s of statuses) counts[s.status] = (counts[s.status] || 0) + 1;
  return counts;
}

function projectView(world, graph, statuses) {
  const next = nextUp(statuses);
  const view = {
    slug: graph.slug, name: graph.project, root: graph.root, links: graph.links,
    problems: graph.problems, units: statuses, counts: countBy(statuses), nextUp: next,
  };
  if (next.key) view.nextUp.prompt = startPrompt(world, world.units.get(next.key));
  return view;
}

export function buildBoard(home) {
  const world = buildWorld(home);
  const byProject = allStatuses(world);
  const projects = world.graphs.map((g) => projectView(world, g, byProject.get(g.slug)));
  const queue = buildQueue(world);
  const graphed = new Set(world.graphs.map((g) => g.slug));
  return { generated: new Date().toISOString(), projects, queue, legacy: legacyCards(home, graphed) };
}

const cell = (t) => String(t ?? '').replace(/\|/g, '/').replace(/\r?\n/g, ' ');

function projectSection(p) {
  if (!p.units.length) {
    return [`### ${p.name}`, '', `Tracked on its own board: ${p.links.join(', ') || '(no link)'}. GMSD never starts or gates it.`, ''];
  }
  const next = p.nextUp.unit ? `**Next up:** ${p.nextUp.unit}` : `**Next up:** none (${cell(p.nextUp.none)})`;
  const lines = [`### ${p.name}`, '', next, '', '| Unit | Status | Owner | Why |', '|---|---|---|---|'];
  for (const u of p.units) lines.push(`| ${u.id} | ${u.status} | ${cell(u.owner)} | ${cell(u.reason)} |`);
  if (p.problems.length) lines.push('', `Graph problems: ${p.problems.join('; ')}`);
  return [...lines, ''];
}

export function renderStatusMd(board) {
  const lines = [
    '# STATUS (generated)',
    '',
    `Generated by \`npm run board\` at ${board.generated} from the disk. Do not edit by hand; edit a project's graph.md or its own files.`,
    '',
    `## Waiting on Jeff (${board.queue.open.length})`,
    '',
  ];
  for (const it of board.queue.open) {
    lines.push(`- **${it.question}** (${it.gate}; open \`${it.open}\`) Answers: ${it.answers.map((a) => `${a.key}) ${a.label}`).join(' · ')}`);
  }
  lines.push('', '## Projects on the graph', '');
  for (const p of board.projects) lines.push(...projectSection(p));
  lines.push('## Projects with no graph yet', '', 'Their hand-written cards are kept as data. Their typed state is not shown as current.', '');
  lines.push('| Project | Card last edited | Folder |', '|---|---|---|');
  for (const c of board.legacy) lines.push(`| ${cell(c.name)} | ${cell(c.cardUpdated)} | ${cell(c.folder)} |`);
  return `${lines.join('\n')}\n`;
}
